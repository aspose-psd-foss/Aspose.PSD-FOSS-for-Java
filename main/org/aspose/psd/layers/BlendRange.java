package org.aspose.psd.layers;

/**
 * Represents a PSD layer blend range.
 */
public class BlendRange {
    private int destination;
    private int source;

    /**
     * Gets the destination blend range.
     */
    public int getDestination() {
        return destination;
    }

    /**
     * Sets the destination blend range.
     */
    public void setDestination(int destination) {
        this.destination = destination;
    }

    /**
     * Gets the source blend range.
     */
    public int getSource() {
        return source;
    }

    /**
     * Sets the source blend range.
     */
    public void setSource(int source) {
        this.source = source;
    }
}
