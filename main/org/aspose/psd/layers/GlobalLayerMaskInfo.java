package org.aspose.psd.layers;

/**
 * Represents global layer mask information.
 */
public class GlobalLayerMaskInfo {
    /**
     * Empty instance of {@code GlobalLayerMaskInfo}.
     */
    private static final GlobalLayerMaskInfo EMPTY = new GlobalLayerMaskInfo();

    /**
     * Returns an empty global layer mask info instance.
     *
     * @return empty instance
     */
    public static GlobalLayerMaskInfo getEmpty() {
        return EMPTY;
    }

    public static GlobalLayerMaskInfo empty() {
        return getEmpty();
    }
}